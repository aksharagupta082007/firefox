def init_db():
    """Create all tables if they don't exist and seed default assets."""
    Base.metadata.create_all(bind=engine)
    seed_database()


def get_db():
    """FastAPI dependency for DB sessions."""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
